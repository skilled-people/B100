// 잡음 마스크: 멘탈과 연구원 수에 따라 rest 부분이 조금씩 드러난다
export function decodeRecording(rec, reveal) {
  const chars = [...rec.rest];
  const out = chars.map((c, i) => {
    if (c === ' ') return c;
    const h = Math.abs(Math.sin((i + 1) * 12.9898 + rec.floor * 78.233) * 43758.5453) % 1;
    return h < reveal ? c : '▒';
  });
  return rec.lead + out.join('');
}

